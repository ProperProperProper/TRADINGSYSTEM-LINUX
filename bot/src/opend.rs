//! TCP client for the local moomoo OpenD gateway (default 127.0.0.1:11111).
//!
//! Wire format (moomoo SDK `MESSAGE_HEAD_FMT = "<1s1sI2B2I20s8s"`, 44 bytes, little endian):
//! `F` `T`, proto id (u32), body format (u8, 0 = protobuf), protocol version (u8, 0),
//! serial number (u32), body length (u32), SHA-1 of the body (20 bytes), reserved (8 bytes);
//! then the protobuf body. Encryption is only used when an RSA key is configured in OpenD
//! (not supported here: OpenD runs on this machine).

use anyhow::{anyhow, ensure, Context, Result};
use prost::Message;
use sha1::{Digest, Sha1};
use std::time::Duration;
use tokio::io::{AsyncReadExt, AsyncWriteExt};
use tokio::net::TcpStream;

use crate::pb;

pub const DEFAULT_ADDR: &str = "127.0.0.1:11111";
const HEAD_LEN: usize = 44;
/// A reply slower than this is an error (OpenD answers local requests in milliseconds).
const REPLY_TIMEOUT: Duration = Duration::from_secs(30);

