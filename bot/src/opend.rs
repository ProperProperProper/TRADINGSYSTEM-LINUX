/// A reply message: its result code and text, and its payload.
pub trait Reply: Message + Default {
    type S2c;
    /// The reply's (retType, retMsg, errCode).
    fn ret(&self) -> (i32, Option<&str>, Option<i32>);
    /// The reply's payload (S2C), if any.
    fn into_s2c(self) -> Option<Self::S2c>;
}

macro_rules! reply {
    ($($m:ident),* $(,)?) => {$(
        impl Reply for pb::$m::Response {
            type S2c = pb::$m::S2c;
            /// The reply's (retType, retMsg, errCode) (generated for every protocol by `reply!`).
            fn ret(&self) -> (i32, Option<&str>, Option<i32>) {
                (self.ret_type, self.ret_msg.as_deref(), self.err_code)
            }
            /// The reply's payload (S2C), if any (generated by `reply!`).
            fn into_s2c(self) -> Option<Self::S2c> {
                self.s2c
            }
        }
    )*};
}
