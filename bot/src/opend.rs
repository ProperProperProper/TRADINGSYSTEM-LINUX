/// One header + body frame.
pub fn frame(proto_id: u32, serial: u32, body: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(HEAD_LEN + body.len());
    out.extend_from_slice(b"FT");
    out.extend_from_slice(&proto_id.to_le_bytes());
    out.push(0); // protobuf
    out.push(0); // protocol version
    out.extend_from_slice(&serial.to_le_bytes());
    out.extend_from_slice(&(body.len() as u32).to_le_bytes());
    out.extend_from_slice(&Sha1::digest(body));
    out.extend_from_slice(&[0u8; 8]);
    out.extend_from_slice(body);
    out
}

/// Parsed header: (proto id, serial number, body length, body SHA-1).
pub fn parse_head(h: &[u8; HEAD_LEN]) -> Result<(u32, u32, usize, [u8; 20])> {
    ensure!(&h[0..2] == b"FT", "not an OpenD frame (bad magic)");
    ensure!(
        h[6] == 0,
        "OpenD sent body format {} (protobuf expected)",
        h[6]
    );
    let u32_at = |i: usize| u32::from_le_bytes([h[i], h[i + 1], h[i + 2], h[i + 3]]);
    let mut sha = [0u8; 20];
    sha.copy_from_slice(&h[16..36]);
    Ok((u32_at(2), u32_at(8), u32_at(12) as usize, sha))
}

/// OpenD answered, but refused the request (retType != 0). Any other error from `call` is a
/// transport failure (connection lost, timeout, bad frame): the connection should be replaced.
#[derive(Debug, Clone)]
pub struct Refused {
    pub proto: u32,
    pub ret: i32,
    pub code: Option<i32>,
    pub msg: String,
}

impl std::fmt::Display for Refused {
    /// Display text of an OpenD refusal (proto, retType, errCode, message).
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(
            f,
            "OpenD proto {} failed: retType {}, errCode {:?}: {}",
            self.proto, self.ret, self.code, self.msg
        )
    }
}

impl std::error::Error for Refused {}

pub struct OpenD {
    stream: TcpStream,
    serial: u32,
    /// Serial numbers of trading write packets (PacketID, replay protection).
    packet_serial: u32,
    /// OpenD's version and this connection's id (from InitConnect).
    pub server_ver: i32,
    pub conn_id: u64,
    /// Seconds between keep-alives OpenD expects.
    pub keep_alive_secs: i32,
}

impl OpenD {
    /// Connect and run InitConnect. Fails if OpenD is not running or refuses the client.
    pub async fn connect(addr: &str, client_id: &str) -> Result<OpenD> {
        let stream = tokio::time::timeout(Duration::from_secs(5), TcpStream::connect(addr))
            .await
            .map_err(|_| anyhow!("OpenD at {addr} did not accept a connection within 5 s"))?
            .with_context(|| {
                format!("OpenD is not reachable at {addr} (is moomoo OpenD running and logged in?)")
            })?;
        let mut c = OpenD {
            stream,
            serial: 0,
            packet_serial: 0,
            server_ver: 0,
            conn_id: 0,
            keep_alive_secs: 0,
        };
        let s2c = c
            .call::<pb::init_connect::Response>(
                id::INIT_CONNECT,
                &pb::init_connect::Request {
                    c2s: pb::init_connect::C2s {
                        client_ver: 300,
                        client_id: client_id.to_string(),
                        recv_notify: Some(false),
                        packet_enc_algo: Some(-1), // PacketEncAlgo_None
                        push_proto_fmt: Some(0),   // protobuf
                        programming_language: Some("Rust".into()),
                        ..Default::default() // fields added by newer protocol files stay unset
                    },
                },
            )
            .await?;
        c.server_ver = s2c.server_ver;
        c.conn_id = s2c.conn_id;
        c.keep_alive_secs = s2c.keep_alive_interval;
        Ok(c)
    }

    /// Next PacketID serial number for a trading write (place / modify order).
    /// One KeepAlive round trip (proto 1004). The SDK sends it every `keep_alive_interval * 4 / 5` seconds on a long-lived connection; returns OpenD's server time.
    pub async fn keep_alive(&mut self) -> Result<i64> {
        let now = std::time::SystemTime::now()
            .duration_since(std::time::UNIX_EPOCH)
            .map_or(0, |d| d.as_secs() as i64);
        let s2c = self
            .call::<pb::keep_alive::Response>(
                id::KEEP_ALIVE,
                &pb::keep_alive::Request {
                    c2s: pb::keep_alive::C2s { time: now },
                },
            )
            .await?;
        Ok(s2c.time)
    }

    /// Seconds between KeepAlive calls: the SDK's 4/5 of the interval OpenD announced in InitConnect (at least 1).
    pub fn keep_alive_every(&self) -> u64 {
        ((self.keep_alive_secs.max(1) as u64) * 4 / 5).max(1)
    }

    pub fn next_serial(&mut self) -> u32 {
        self.packet_serial = self.packet_serial.wrapping_add(1);
        self.packet_serial
    }

    /// Send one request and return the reply's payload; an OpenD error (retType != 0) is an error.
    /// Pushes and other frames arriving in between are skipped.
    pub async fn call<R: Reply>(&mut self, proto_id: u32, req: &impl Message) -> Result<R::S2c> {
        self.serial = self.serial.wrapping_add(1);
        let serial = self.serial;
        self.stream
            .write_all(&frame(proto_id, serial, &req.encode_to_vec()))
            .await?;
        let body = tokio::time::timeout(REPLY_TIMEOUT, async {
            loop {
                let mut head = [0u8; HEAD_LEN];
                self.stream
                    .read_exact(&mut head)
                    .await
                    .context("OpenD closed the connection")?;
                let (pid, ser, len, sha) = parse_head(&head)?;
                ensure!(len <= 64 << 20, "OpenD frame of {len} bytes");
                let mut body = vec![0u8; len];
                self.stream.read_exact(&mut body).await?;
                ensure!(
                    Sha1::digest(&body)[..] == sha[..],
                    "OpenD frame {pid} failed its SHA-1 check"
                );
                if pid == proto_id && ser == serial {
                    return Ok::<_, anyhow::Error>(body);
                }
            }
        })
        .await
        .map_err(|_| {
            anyhow!(
                "OpenD did not answer proto {proto_id} within {} s",
                REPLY_TIMEOUT.as_secs()
            )
        })??;
        let rsp = R::decode(body.as_slice())
            .with_context(|| format!("OpenD reply {proto_id} is not valid protobuf"))?;
        let (ret, msg, code) = rsp.ret();
        if ret != 0 {
            return Err(Refused {
                proto: proto_id,
                ret,
                code,
                msg: msg.unwrap_or("-").to_string(),
            }
            .into());
        }
        rsp.into_s2c()
            .ok_or_else(|| anyhow!("OpenD proto {proto_id} succeeded without a payload"))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// Test: frames round trip with the sdk header layout.
    #[test]
    fn frames_round_trip_with_the_sdk_header_layout() {
        let body = b"hello";
        let f = frame(3103, 7, body);
        assert_eq!(f.len(), HEAD_LEN + body.len());
        let mut head = [0u8; HEAD_LEN];
        head.copy_from_slice(&f[..HEAD_LEN]);
        let (pid, ser, len, sha) = parse_head(&head).unwrap();
        assert_eq!((pid, ser, len), (3103, 7, 5));
        assert_eq!(&sha[..], &Sha1::digest(body)[..]);
        assert_eq!(&f[HEAD_LEN..], body);
        assert!(parse_head(&[0u8; HEAD_LEN]).is_err(), "bad magic");
    }

    /// Test: requests encode with generated types.
    #[test]
    fn the_keep_alive_period_is_four_fifths_of_the_announced_interval_like_the_sdk() {
        let mut c = tokio::runtime::Builder::new_current_thread()
            .enable_all()
            .build()
            .unwrap()
            .block_on(async {
                let l = tokio::net::TcpListener::bind("127.0.0.1:0").await.unwrap();
                let addr = l.local_addr().unwrap();
                let s = TcpStream::connect(addr).await.unwrap();
                OpenD {
                    stream: s,
                    serial: 0,
                    packet_serial: 0,
                    server_ver: 0,
                    conn_id: 0,
                    keep_alive_secs: 10,
                }
            });
        assert_eq!(c.keep_alive_every(), 8);
        c.keep_alive_secs = 0;
        assert_eq!(c.keep_alive_every(), 1);
    }

    #[test]
    fn requests_encode_with_generated_types() {
        let req = pb::get_global_state::Request {
            c2s: pb::get_global_state::C2s { user_id: 0 },
        };
        let back = pb::get_global_state::Request::decode(req.encode_to_vec().as_slice()).unwrap();
        assert_eq!(back.c2s.user_id, 0);
    }
}
